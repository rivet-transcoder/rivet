//! DTS Coherent Acoustics **core** decoder (ETSI TS 102 114 V1.6.1, clause 5).
//!
//! Decodes the core substream — up to five full-range channels plus LFE at
//! ≤ 48 kHz — to interleaved f32 PCM so a DTS track can be transcoded to
//! Opus. Extensions are not decoded: XCh/XXCh/X96 data inside the core frame
//! and any DTS-HD extension substream after it are skipped, so a DTS-HD
//! track yields its (lossy) core, which is what legacy DTS decoders play.
//!
//! What is implemented follows the spec's own decoding procedure: the bit
//! stream and primary audio coding headers (Tables 5-1, 5-21), the per-
//! subframe side information (5-28), the audio arrays (5-29) with Huffman,
//! block-code and linear quantisation index decoding, transient-split scale
//! factors, joint intensity coding, front/surround sum-difference decoding,
//! dynamic range control, the 32-band QMF synthesis and the 64×/128× LFE
//! interpolation (Annex C.3). Every table is transcribed from the ETSI text
//! (`tables.rs`, generated by `crates/codec/tools/dts_gen_tables.py`).
//!
//! Two codebooks are missing from every ETSI edition of the spec ("Due to
//! its extensive size, this table is not included here", D.10 — and the DTS
//! patents describe them without printing them), and the licence rule for
//! this decoder forbids taking them from any other decoder's source:
//!
//! - **ADPCM prediction coefficients (D.10.1)**: a subband coded with
//!   `PMODE` = 1 carries prediction residuals, and without the 4096-vector
//!   codebook the prediction cannot be inverted. Such frames are refused by
//!   name ([`DtsError::Unsupported`]) rather than decoded wrongly; the job
//!   layer turns that into "dropped, with the reason". This matters in
//!   practice: ffmpeg's `dca` encoder never predicts, so its streams decode
//!   completely, but a commercial DTS-HD MA track measured on 2026-09-13
//!   (60 s of its core, 5 637 frames) predicted at least one subband in
//!   91 % of frames (3.3 % of all subbands), so most disc-sourced DTS
//!   refuses. Verified against libavcodec on ffmpeg-made vectors to ~1e-6
//!   relative RMS (`crates/codec/tests/dts_core.rs`).
//! - **High-frequency VQ (D.10.2)**: subbands from `VQSUB` up are carried as
//!   a single 10-bit vector index. The spec itself allows ignoring them
//!   ("In case of insufficient MIPS, the VQs for the highest frequency
//!   subbands may be ignored without causing audible distortion", §5.4.3),
//!   so they decode as silence, with one warning per decoder instance. The
//!   same commercial track VQ-coded subbands 28–31 (21–24 kHz) in every
//!   frame.
//!
//! Output order per channel count is the RFC 7845 family-1 order the rest of
//! the audio pipeline uses (`5.1(side)` = FL FR FC LFE SL SR, `2.1` = FL FR
//! LFE), mapped from the core's `AMODE` order. Arrangements the pipeline has
//! no named layout for are refused by name rather than emitted mislabelled.
//!
//! Not applied: dialog normalisation (`DNG`), which is a playback-level
//! adjustment, and the embedded down-mix coefficients.

